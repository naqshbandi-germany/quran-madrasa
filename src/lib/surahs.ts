export const SURAH_OPTIONS = SURAHS.map(([name, ayahs], index) => ({
  number: index + 1,
  name,
  ayahs,
}));

export function surahAyahCount(surah: number) {
  return SURAHS[surah - 1]?.[1] ?? null;
}

// z. B. "Sure 67 Al-Mulk, Vers 12"
export function formatSurahPosition(surah: number | null, ayah: number | null) {
  if (!surah) return null;
  const name = SURAHS[surah - 1]?.[0];
  const base = `Sure ${surah}${name ? ` ${name}` : ""}`;
  return ayah ? `${base}, Vers ${ayah}` : base;
}

